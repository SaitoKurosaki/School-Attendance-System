        private void LoadStudentClasses()
        {
            const string query = @"
                SELECT s.id AS StudentId, cc.ID AS ClassCodeId,
                    CONCAT(s.full_name, ' • ', s.student_number, ' • ', c.COURSE_NAME,
                        ' • Year ', sec.YEAR_LEVEL, ' / Semester ', sec.SEMESTER,
                        ' / Section ', sec.SECTION_NAME) AS StudentClassLabel
                FROM students s
                INNER JOIN class_codes cc ON JSON_CONTAINS(s.classcode, JSON_QUOTE(cc.CLASS_CODE))
                INNER JOIN course c ON c.ID = cc.COURSE_ID
                INNER JOIN section sec ON sec.ID = cc.SECTION_ID
                WHERE sec.IS_ARCHIVED = 0
                    AND sec.SECTION_NAME NOT LIKE 'ARCHIVED-%'
                ORDER BY s.full_name, c.COURSE_NAME, sec.YEAR_LEVEL, sec.SEMESTER, sec.SECTION_NAME;";
            try
            {
                using MySqlConnection connection = new MySqlConnection(Connection);
                using MySqlDataAdapter adapter = new MySqlDataAdapter(query, connection);
                DataTable table = new DataTable();
                adapter.Fill(table);
                studentClassCombo.DisplayMember = "StudentClassLabel";
                studentClassCombo.DataSource = table;
                if (table.Rows.Count == 0)
                    recordCountLabel.Text = "No active student/class assignments.";
            }
            catch (MySqlException)
            {
                recordCountLabel.Text = "Unable to load student/class options. Check the database connection.";
            }
        }

        private StudentClass? SelectedStudentClass()
        {
            if (studentClassCombo.SelectedItem is not DataRowView row ||
                !AppTheme.TryGetIntValue(row["StudentId"], out int studentId) ||
                !AppTheme.TryGetIntValue(row["ClassCodeId"], out int classCodeId))
                return null;
            return new StudentClass(studentId, classCodeId);
        }

        private void AddTestRecords(object? sender, EventArgs e)
        {
            StudentClass? selected = SelectedStudentClass();
            int absences = Decimal.ToInt32(absentCount.Value);
            int lates = Decimal.ToInt32(lateCount.Value);
            if (selected == null)
            {
                recordCountLabel.Text = "Select a student/class first.";
                return;
            }
            if (absences + lates == 0)
            {
                recordCountLabel.Text = "Enter an absence or late count first.";
                return;
            }
            try
            {
                using MySqlConnection connection = new MySqlConnection(Connection);
                connection.Open();
                using MySqlTransaction transaction = connection.BeginTransaction();
                HashSet<DateTime> usedDates = new HashSet<DateTime>();
                using (MySqlCommand existing = new MySqlCommand(@"
                    SELECT ATTENDANCE_DATE FROM attendance_records
                    WHERE STUDENT_ID = @StudentId AND CLASS_CODE_ID = @ClassCodeId;", connection, transaction))
                {
                    existing.Parameters.AddWithValue("@StudentId", selected.StudentId);
                    existing.Parameters.AddWithValue("@ClassCodeId", selected.ClassCodeId);
                    using MySqlDataReader reader = existing.ExecuteReader();
                    while (reader.Read()) usedDates.Add(Convert.ToDateTime(reader[0]).Date);
                }

                List<DateTime> freeDates = new List<DateTime>(absences + lates);
                for (DateTime date = DateTime.Today; freeDates.Count < absences + lates && date.Year >= 2000; date = date.AddDays(-1))
                    if (!usedDates.Contains(date.Date)) freeDates.Add(date.Date);

                if (freeDates.Count < absences + lates)
                {
                    transaction.Rollback();
                    recordCountLabel.Text = "Could not find enough unused dates for those test records.";
                    return;
                }

                using MySqlCommand insert = new MySqlCommand(@"
                    INSERT INTO attendance_records
                        (STUDENT_ID, CLASS_CODE_ID, ATTENDANCE_DATE, STATUS, IS_EXCUSED, TIME_IN, REMARKS)
                    VALUES (@StudentId, @ClassCodeId, @Date, @Status, 0, NULL, @Remark);", connection, transaction);
                insert.Parameters.AddWithValue("@StudentId", selected.StudentId);
                insert.Parameters.AddWithValue("@ClassCodeId", selected.ClassCodeId);
                insert.Parameters.Add("@Date", MySqlDbType.Date);
                insert.Parameters.Add("@Status", MySqlDbType.VarChar);
                insert.Parameters.AddWithValue("@Remark", TestRemark);

                int index = 0;
                for (int i = 0; i < absences; i++, index++)
                {
                    insert.Parameters["@Date"].Value = freeDates[index];
                    insert.Parameters["@Status"].Value = "Absent";
                    insert.ExecuteNonQuery();
                }
                for (int i = 0; i < lates; i++, index++)
                {
                    insert.Parameters["@Date"].Value = freeDates[index];
                    insert.Parameters["@Status"].Value = "Late";
                    insert.ExecuteNonQuery();
                }
                transaction.Commit();
                absentCount.Value = 0;
                lateCount.Value = 0;
                recordCountLabel.Text = string.Empty;
            }
            catch (MySqlException)
            {
                recordCountLabel.Text = "Unable to add test records. Check the database connection.";
            }
        }

        private void RemoveTestRecords(object? sender, EventArgs e)
        {
            StudentClass? selected = SelectedStudentClass();
            if (selected == null)
            {
                recordCountLabel.Text = "Select a student/class first.";
                return;
            }
            try
            {
                using MySqlConnection connection = new MySqlConnection(Connection);
                using MySqlCommand command = new MySqlCommand(@"
                    DELETE FROM attendance_records
                    WHERE STUDENT_ID = @StudentId AND CLASS_CODE_ID = @ClassCodeId AND REMARKS = @Remark;", connection);
                command.Parameters.AddWithValue("@StudentId", selected.StudentId);
                command.Parameters.AddWithValue("@ClassCodeId", selected.ClassCodeId);
                command.Parameters.AddWithValue("@Remark", TestRemark);
                connection.Open();
                command.ExecuteNonQuery();
                recordCountLabel.Text = string.Empty;
            }
            catch (MySqlException)
            {
                recordCountLabel.Text = "Unable to remove test records. Check the database connection.";
            }
        }
